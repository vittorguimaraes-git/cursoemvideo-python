# Polimorfismo

# Function Overload:

print(len("Gustavo Guanabara")) # — > Retorna a quantidade de letras na ‘string’.
print(len(["Curso", "Python"])) # — > Retorna a quantidade de elementos na lista.
print(len({"nome" : "Maria", "idade" : 22})) # — > Retorna a quantidade de elementos no dicionário.

# Ou seja, uma mesma função pode executar de várias formas um ação

# Operator Overload:

print(+12) # — > indica que o número cinco é positivo.
print(5 + 2) # — > indica a soma de dois números.
print("Poli" + "morfismo") # — > indica a concatenação de duas ‘strings’.
print([1, 2, 3, 4] + [9, 7]) # — > une as duas listas e cria uma com os respectivos elementos.

# Da mesma forma um operador também pode ser utilizado de diversas formas dependendo do seu
# contexto