def dobro(valor):
    valor = valor * 2
    return valor

def metade(valor):
    valor = valor / 2
    return valor

def aumentar(valor, porcertagem):
    valor = valor + (valor * porcertagem / 100)
    return valor

def diminuir(valor, porcertagem):
    valor = valor - (valor * porcertagem / 100)
    return valor
